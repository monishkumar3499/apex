-- ============================================================================
-- Kairo · AI Prep Engine — PostgreSQL / Supabase schema
-- ============================================================================
-- Run this whole file once in the Supabase SQL editor. It is idempotent.
--
-- Design notes
--   * Every user-owned row carries user_id and is protected by RLS.
--   * The background build pipeline runs with the service-role key, which
--     bypasses RLS by design. Client reads always go through RLS.
--   * `blueprint_cache` is global (service-role only) so a plan skeleton
--     computed for "GATE ECE / beginner / 6mo" is reused across users
--     instead of being re-generated by the model every time.
-- ============================================================================

