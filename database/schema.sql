-- Every other user-owned table gets the identical owner policy.
do $$
declare t text;
begin
  foreach t in array array[
    'plans','plan_events','units','topics','resources','topic_resources',
    'sessions','session_items','questions','reviews','mocks','study_logs',
    'chats','messages'
  ] loop
    execute format('drop policy if exists %I on public.%I', t || '_owner', t);
    execute format(
      'create policy %I on public.%I for all
         using (auth.uid() = user_id) with check (auth.uid() = user_id)',
      t || '_owner', t);
  end loop;
end $$;

