-- 2. plans
-- ---------------------------------------------------------------------------
create table if not exists public.plans (
  id              uuid primary key default gen_random_uuid(),
  user_id         uuid        not null references auth.users(id) on delete cascade,

  title           text        not null,
  prep_type       prep_type   not null default 'skill',
  subject_slug    text,
  status          plan_status not null default 'draft',

  start_date      date        not null default current_date,
  target_date     date        not null,
  weekday_minutes int         not null default 120,
  weekend_minutes int         not null default 240,
  rest_days       int[]       not null default '{}',   -- 0=Sun … 6=Sat

  skill_level     text        not null default 'beginner',
  intake          jsonb       not null default '{}'::jsonb,
  blueprint       jsonb       not null default '{}'::jsonb,
  digest          text,

  total_items     int         not null default 0,
  done_items      int         not null default 0,

  build_error     text,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),

  constraint plans_dates_ck check (target_date > start_date)
);
create index if not exists plans_user_idx    on public.plans(user_id, created_at desc);
create index if not exists plans_subject_idx on public.plans(subject_slug);

