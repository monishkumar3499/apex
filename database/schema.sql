create or replace function public.touch_updated_at()
returns trigger language plpgsql as $fn$
begin new.updated_at = now(); return new; end $fn$;

drop trigger if exists tr_profiles_touch on public.profiles;
create trigger tr_profiles_touch before update on public.profiles
  for each row execute function public.touch_updated_at();

drop trigger if exists tr_plans_touch on public.plans;
create trigger tr_plans_touch before update on public.plans
  for each row execute function public.touch_updated_at();

create or replace function public.sync_plan_counters()
returns trigger language plpgsql security definer set search_path = public as $fn$
declare pid uuid;
begin
  pid := coalesce(new.plan_id, old.plan_id);
  update public.plans p
     set total_items = sub.total,
         done_items  = sub.done
    from (
      select count(*)::int as total,
             count(*) filter (where status = 'done')::int as done
        from public.session_items where plan_id = pid
    ) sub
   where p.id = pid;
  return coalesce(new, old);
end $fn$;

drop trigger if exists tr_items_counters on public.session_items;
create trigger tr_items_counters
  after insert or update of status or delete on public.session_items
  for each row execute function public.sync_plan_counters();

